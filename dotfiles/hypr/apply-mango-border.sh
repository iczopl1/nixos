#!/usr/bin/env bash
# Sets mango window border colors from the wal palette, fading old -> new.
# MANGO_FADE_MS / MANGO_FADE_STEPS control the fade. Needs ~/.cache/wal/colors.sh.
set -euo pipefail

CACHE_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/wal"
COLORS_SH="$CACHE_DIR/colors.sh"
BRIGHTNESS_BOOST="${BRIGHTNESS_BOOST:-48}"
INACTIVE_DARKEN="${INACTIVE_DARKEN:-36}"
[ -f "$COLORS_SH" ] || exit 0
set +u; source "$COLORS_SH"; set -u

shift_hex() {  # hex, amount (negative darkens), clamped per channel
  local hex="${1#\#}" d="$2" r g b
  r=$((16#${hex:0:2} + d)); g=$((16#${hex:2:2} + d)); b=$((16#${hex:4:2} + d))
  for v in r g b; do (( ${!v} > 255 )) && printf -v "$v" 255; (( ${!v} < 0 )) && printf -v "$v" 0; done
  printf '#%02x%02x%02x' "$r" "$g" "$b"
}

active_start="$(shift_hex "$color12" "$BRIGHTNESS_BOOST")"
inactive="$(shift_hex "$color8" "-$INACTIVE_DARKEN")"

if [ -d "$HOME/.config/mango" ]; then
  MANGO_WAL="$HOME/.config/mango/mango-wal.conf"
  old_focus="$(sed -n 's/^focus_color=0x\([0-9a-fA-F]\{6\}\)ff$/\1/p' "$MANGO_WAL" 2>/dev/null || true)"
  old_border="$(sed -n 's/^border_color=0x\([0-9a-fA-F]\{6\}\)ff$/\1/p' "$MANGO_WAL" 2>/dev/null || true)"
  new_focus="${active_start#\#}"
  new_border="${inactive#\#}"
  printf '# Auto-generated by wal-apply-theme.sh\nfocus_color=0x%sff\nborder_color=0x%sff\n' \
    "$new_focus" "$new_border" > "$MANGO_WAL"
  # Mango does not animate border colors, so step them with setoption (runtime only).
  # Old colors come from the file just replaced; without them the border just snaps.
  if command -v mmsg >/dev/null 2>&1; then
    B_MS="${MANGO_FADE_MS:-2500}"
    B_STEPS="${MANGO_FADE_STEPS:-1}"   # 1 = snap; every setoption makes mango re-update all windows
    B_GEN_FILE="$CACHE_DIR/mango-fade.gen"
    B_GEN="$$.$RANDOM"
    printf '%s' "$B_GEN" > "$B_GEN_FILE"
    (
      if [ -z "$old_focus" ] || [ -z "$old_border" ]; then
        old_focus="$new_focus"; old_border="$new_border"; B_STEPS=1
      fi
      nap="$(awk "BEGIN { printf \"%.3f\", $B_MS / 1000 / $B_STEPS }")"
      while read -r f b; do
        [ "$(cat "$B_GEN_FILE" 2>/dev/null)" = "$B_GEN" ] || exit 0
        mmsg dispatch "setoption,focus_color,0x${f}ff" >/dev/null 2>&1 || true
        mmsg dispatch "setoption,border_color,0x${b}ff" >/dev/null 2>&1 || true
        sleep "$nap"
      done < <(awk -v n="$B_STEPS" -v of="$old_focus" -v nf="$new_focus" -v ob="$old_border" -v nb="$new_border" '
        function hx(s, p,  i,v,d) { v=0; s=tolower(s)
          for (i=p;i<p+2;i++) { d=index("0123456789abcdef",substr(s,i,1))-1; v=v*16+d } return v }
        function mix(a, z, u) {
          return sprintf("%02x%02x%02x",
            int(hx(a,1)+(hx(z,1)-hx(a,1))*u+0.5),
            int(hx(a,3)+(hx(z,3)-hx(a,3))*u+0.5),
            int(hx(a,5)+(hx(z,5)-hx(a,5))*u+0.5)) }
        BEGIN { for (k=1;k<=n;k++) { u=k/n; u=u*u*(3-2*u); print mix(of,nf,u), mix(ob,nb,u) } }')
    ) >/dev/null 2>&1 &
  fi
fi

